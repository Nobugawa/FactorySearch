const fs=require('fs');
const {evaluateQuote,compareSet}=require('../quote.js');
let f=0,n=0;const ok=(c,m)=>{n++;if(!c){f++;console.log('FAIL',m);}};
const TODAY='2026-11-07';
const common={drawing:'D-1',revision:'A',spec:'print',material:'4140',finish:'none',inspection:'standard',shipTo:'Mahwah NJ',currency:'USD'};
function leg(status,amount,basis){return {status:status,amount:amount==null?'':String(amount),basis:basis||''};}
function legs(over){return Object.assign({carriage:leg('na'),insurance:leg('na'),duties:leg('na'),broker:leg('na'),packaging:leg('na'),destination:leg('na')},over||{});}
function base(over){return Object.assign({kind:'quote',quoteDate:'2026-11-01',validity:'2026-12-01',moq:'1',prodValue:'4',prodUnit:'weeks',transitValue:'3',transitUnit:'weeks',incoterm:'EXW',namedPlace:'Xiamen',currency:'USD',fx:'',unitPrice:'10',tooling:'',spreadTooling:false,legs:legs()},over);}
function ev(sup,qty,c,today){return evaluateQuote(c||common,sup,qty==null?10:qty,{today:today||TODAY});}
let r=ev(base());
ok(r.complete&&r.landedUnit===10&&r.unitRecurring===10&&r.oneTime==null&&r.shipmentPerUnit===0,'explicit not-applicable charges add nothing and do not invent tooling');
r=ev(base({legs:legs({carriage:leg('','')})}));
ok(r.landedUnit==null&&r.gaps.includes('Carriage in the seller price is unknown'),'a blank charge is unknown, not zero');
r=ev(base({legs:legs({carriage:leg('buyer','-1','unit')})}));
ok(r.landedUnit==null&&r.gaps.some(g=>/Carriage/.test(g)&&/negative/.test(g)),'negative freight is rejected');
r=ev(base({legs:legs({carriage:leg('buyer','0','unit')})}));
ok(r.complete&&r.landedUnit===10,'an explicit zero buyer charge is kept');
r=ev(base({legs:legs({carriage:leg('buyer','500','shipment')})}),10);
ok(r.complete&&r.shipmentPerUnit===50&&r.landedUnit===60,'a 500 shipment charge at quantity 10 is 50 per piece');
r=ev(base({legs:legs({carriage:leg('buyer','500','shipment')})}),1000);
ok(r.complete&&r.shipmentPerUnit===0.5&&r.landedUnit===10.5,'the same 500 shipment charge at quantity 1000 is 0.50 per piece');
r=ev(base({currency:'EUR',fx:'1.1',unitPrice:'12',legs:legs({destination:leg('buyer','500','shipment')})}));
ok(r.unitRecurring===13.2&&r.landedUnit===63.2,'the rate converts the unit price only; a buyer charge stays in the comparison currency');
r=ev(base({currency:'EUR',fx:''}));
ok(r.landedUnit==null&&r.gaps.includes('FX rate'),'missing FX blocks conversion');
r=ev(base({currency:'EUR',fx:'0'}));
ok(r.landedUnit==null,'FX of zero is rejected');
r=ev(base({currency:'EUR',fx:'-2'}));
ok(r.landedUnit==null,'negative FX is rejected');
r=ev(base({fx:'9'}));
ok(r.unitRecurring===10&&r.landedUnit===10,'the same currency uses a rate of 1');
r=ev(base({tooling:'100',spreadTooling:true}));
ok(r.oneTime===100&&r.landedUnit===20,'tooling in the price currency is spread across this order quantity');
r=ev(base({tooling:'100',spreadTooling:false}));
ok(r.oneTime===100&&r.landedUnit===10&&r.flags.some(x=>/one-time/.test(x)),'tooling stays out of the unit until it is spread');
r=ev(base({unitPrice:''}));
ok(r.unitRecurring==null&&r.landedUnit==null,'blank unit price is not zero');
r=ev(base(),'10, 1000');
ok(r.landedUnit==null&&r.qty==null&&r.gaps.includes('quantity must be one positive whole number'),'a comma-separated list is not a set of price tiers');
r=ev(base(),'10.5');
ok(r.landedUnit==null,'quantity has to be a positive whole number');
r=ev(base({moq:'500'}));
ok(r.landedUnit==null&&r.complete===false&&r.gaps.includes('quantity is below MOQ'),'quantity 10 does not clear an MOQ of 500');
r=ev(base({validity:'2025-01-01',quoteDate:'2025-01-01'}));
ok(r.landedUnit==null&&r.gaps.includes('quote expired'),'an expired quote is not a complete cost');
r=ev(base({quoteDate:'2026-11-06',validity:'2026-11-05'}));
ok(r.gaps.includes('validity is before the quote date')&&r.gaps.includes('quote expired'),'validity before the quote date is rejected');
r=ev(base({quoteDate:'2026-11-08',validity:'2026-12-01'}));
ok(r.landedUnit==null&&r.gaps.includes('quote date is after today'),'a quote date after today is rejected');
r=ev(base({quoteDate:'2026-11-07',validity:'2026-11-07'}));
ok(r.complete,'a quote dated today and valid through today can be complete');
r=ev(base({prodValue:'-1'}));
ok(r.landedUnit==null&&r.gaps.some(g=>/production lead/.test(g)),'a negative production lead is rejected');
r=ev(base({prodValue:'4',prodUnit:''}));
ok(r.landedUnit==null&&r.gaps.includes('production lead unit'),'a lead time needs a unit');
r=ev(base({transitValue:'0',transitUnit:'days'}));
ok(r.complete,'a zero transit with a unit is a real zero');
r=ev(base({incoterm:'DAP',legs:legs({insurance:leg('')})}));
ok(r.landedUnit==null&&r.gaps.includes('Insurance is unknown'),'DAP does not treat insurance as included');
r=ev(base({incoterm:'DAP',legs:legs({insurance:leg('na')})}));
ok(r.complete&&r.landedUnit===10,'DAP can be completed by marking insurance not applicable');
r=ev(base({incoterm:'CFR',legs:legs({carriage:leg('included'),destination:leg('buyer','500','shipment')})}));
ok(r.complete&&r.landedUnit===60,'CFR can include seller carriage and still add a buyer charge through the ship-to');
r=ev(base({incoterm:'CIF',legs:legs({carriage:leg('included','5')})}));
ok(r.landedUnit==null&&r.gaps.includes('double-count Carriage in the seller price'),'an amount on top of a charge marked included is a double-count');
r=ev(base({incoterm:'DDP',legs:legs({broker:leg('buyer','4','unit'),packaging:leg('included')})}));
ok(r.complete&&r.landedUnit===14,'DDP does not forbid a separate brokerage amount');
r=ev(base({incoterm:'DDP',legs:legs({packaging:leg('included','3')})}));
ok(r.landedUnit==null&&r.gaps.includes('double-count Packaging'),'packaging marked included cannot also carry an amount');
r=ev(base(),10,{drawing:'',revision:'',spec:'',material:'',finish:'',inspection:'',shipTo:'',currency:'USD'});

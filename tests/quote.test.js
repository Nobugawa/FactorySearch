ok(compareSet([a,ev(base({namedPlace:'xiamen'}))]).ok===true&&compareSet([a,ev(base({unitPrice:'12'}))]).mode==='quote','matching Incoterm and named place can compare quotes');
ok(compareSet([ev(base({kind:'estimate'})),ev(base({kind:'estimate',unitPrice:'12'}))]).mode==='estimate','two estimates stay an estimate scenario');
ok(compareSet([a,ev(base({kind:'estimate',unitPrice:'12'}))]).ok===false,'an estimate is not compared with a supplier quote');
ok(compareSet([a]).ok===false,'one complete quote is not a comparison');
const other=ev(base(),10,Object.assign({},common,{shipTo:'Houston'}));

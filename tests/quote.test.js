const {evaluateQuote,compareSet}=require('../quote.js');
let f=0,n=0;const ok=(c,m)=>{n++;if(!c){f++;console.log('FAIL',m);}};
const common={drawing:'D-1',revision:'A',shipTo:'Mahwah NJ',currency:'USD'};
function base(over){return Object.assign({kind:'quote',quoteDate:'2026-11-07',validity:'2026-12-07',moq:'1',prod:'4 weeks',transit:'3 weeks',incoterm:'EXW',namedPlace:'factory',currency:'USD',fx:'',unitPrice:'10',tooling:'',amortQty:'',freight:'2',insurance:'1',broker:'0',packaging:'0',duties:'0'},over);}
let r=evaluateQuote(common,base(),10);
ok(r.complete&&r.landedUnit===13&&r.unitRecurring===10&&r.oneTime==null,'EXW adds explicit extras and does not invent tooling');
r=evaluateQuote(common,base({freight:''}),10);
ok(r.landedUnit==null&&r.gaps.includes('freight'),'blank freight is missing, not zero');
r=evaluateQuote(common,base({freight:'-1'}),10);
ok(r.landedUnit==null&&r.gaps.some(g=>/freight/.test(g)),'negative freight is rejected');
r=evaluateQuote(common,base({incoterm:'CIF',freight:'',insurance:''}),10);
ok(r.complete&&r.landedUnit===10,'CIF does not require a second freight or insurance amount');
r=evaluateQuote(common,base({incoterm:'CIF',freight:'5',insurance:''}),10);
ok(r.landedUnit==null&&r.gaps.includes('double-count freight'),'CIF freight is a double-count');
r=evaluateQuote(common,base({incoterm:'DDP',duties:'4'}),10);
ok(r.landedUnit==null&&r.gaps.includes('double-count duties'),'DDP duties are a double-count');
r=evaluateQuote(common,base({currency:'EUR',fx:''}),10);
ok(r.landedUnit==null&&r.gaps.includes('FX rate'),'missing FX blocks conversion');
r=evaluateQuote(common,base({currency:'EUR',fx:'1.1'}),10);
ok(r.unitRecurring===11&&r.landedUnit===14,'FX converts the unit price; extras are amounts you already entered in the comparison currency');
r=evaluateQuote(common,base({currency:'EUR',fx:'0'}),10);
ok(r.landedUnit==null,'FX of zero is rejected');
r=evaluateQuote(common,base({currency:'EUR',fx:'-2'}),10);
ok(r.landedUnit==null,'negative FX is rejected');
r=evaluateQuote(common,base({tooling:'100',amortQty:'10'}),10);
ok(r.oneTime===100&&r.landedUnit===23,'tooling is one-time and can be spread only when a quantity is entered');
r=evaluateQuote(common,base({tooling:'100',amortQty:''}),10);
ok(r.oneTime===100&&r.landedUnit===13&&r.flags.some(x=>/one-time/.test(x)),'tooling without a spread quantity stays out of the unit');
r=evaluateQuote(common,base({unitPrice:''}),10);
ok(r.unitRecurring==null&&r.landedUnit==null,'blank unit price is not zero');
r=evaluateQuote({drawing:'',revision:'',shipTo:'',currency:'USD'},base(),10);
ok(r.landedUnit==null&&r.complete===false&&r.gaps.includes('ship-to'),'a missing ship-to blocks the landed total');
const a=evaluateQuote(common,base(),10), b=evaluateQuote(common,base({incoterm:'FOB',namedPlace:'Shanghai'}),10);
ok(compareSet([a,b]).ok===false,'different Incoterms are not comparable');
ok(compareSet([a,evaluateQuote(common,base({unitPrice:'12'}),10)]).ok===true,'same Incoterm can be compared');
ok(compareSet([a]).ok===false,'one complete quote is not a comparison');
ok(compareSet([a,evaluateQuote(common,base({unitPrice:'12',validity:''}),10)]).ok===false,'a missing validity date blocks the comparison');
r=evaluateQuote(common,base({freight:'0'}),10);
ok(r.landedUnit===11,'an explicit zero freight is kept, and a blank is not turned into zero');
r=evaluateQuote(common,base({duties:''}),10);
ok(r.landedUnit==null&&r.gaps.includes('duties'),'a blank duty is not filled with a default rate');
r=evaluateQuote(common,base({fx:'9'}),10);
ok(r.unitRecurring===10&&r.landedUnit===13,'the same currency uses a rate of 1');
console.log(n,'checks',f,'failures');process.exit(f?1:0);
